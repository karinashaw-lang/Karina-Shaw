// MVP_BUILD_INSTRUCTIONS.md items 2.3/2.4: the server-side rendering
// function Global Rule 11 ("All paywall enforcement is server-side.
// Client-side gating is cosmetic.") has needed since the entitlements
// system existed. Until this function existed, every export format
// rendered entirely client-side with no entitlement check anywhere
// (confirmed directly by MVP_INSTRUCTIONS_STATUS.md's audit) -- the
// product could not actually charge for anything it already had a
// working Stripe flow for.
//
// Verify session -> verify entitlement -> assemble content from the
// SAME engine app.js uses (../_shared/document_engine.mjs, proven
// byte-identical to the live client by
// tests/release_document/test_document_engine_parity.js, not just
// asserted to be) -> render -> upload to the private "documents"
// bucket -> short-lived signed URL -> audit_log row -> increment
// exports_used.
//
// Scope cut, stated plainly rather than silently: this renders from
// the bundled launch-set data (data/launch_set_*.json, regenerated by
// tools/build_release_bundle.py) and refuses any documentId outside
// the approved launch set (LAUNCH_SET_PROPOSAL.md) -- consistent with
// "only launch-set documents are published, promoted and sold."
// Signature and next-steps sections are omitted from the rendered
// output, the same cut document_engine.mjs's buildDocumentContent()
// already documents, for the same reason (no server-side equivalent
// of that client-only state exists yet). The sources appendix is the
// same kind of cut -- it's gated by state.includeSourcesAppendix, a
// client-only UI toggle with no server equivalent, same as signature/
// next-steps above.
//
// MVP_FINISH_VERIFY_SHARPEN.md item 1.1's PDF/DOCX-vs-on-screen-preview
// comparison found this file's rendered output was missing three
// things the client's own buildPdfDocDefinition()/buildDocxDocument()
// already had, none of them disclosed above as an intentional cut --
// a real gap, not a documented scope decision: the jurisdiction notice
// (now classifyDocumentJurisdiction()/JURISDICTION_NOTICE, ported into
// document_engine.mjs), a real per-page/footer-section document-id-
// and-generated-date footer (this file's own renderPdf/renderDocx had
// no footer at all, just a body line with different wording than the
// client's), and the verify-page link (now verifyPageUrl(), reading
// the same config/seo.json baseUrl the client does, bundled at build
// time into data/launch_set_meta.json by build_release_bundle.py).
// All three are fixed below. No QR code exists anywhere in this
// product, client or server -- confirmed by grepping app.js, not
// assumed -- so there is no QR-code gap to close here, only a verify
// *link*, which is what both renderers actually produce.
//
// Verification note, stated as plainly as every other edge function's
// own comment does: the auth/entitlement/assembly/storage/audit_log
// path was checked with `tsc` against hand-written stubs (no `deno`
// binary in this sandbox -- see DECISIONS.md) and reviewed line by
// line. The actual PDF (npm:pdf-lib) and DOCX (npm:docx) rendering
// calls are the ONE part of this whole file that could not be
// type-checked against the real libraries at all: installing pdf-lib
// and docx locally to test against was refused by this sandbox's own
// oversight classifier (an autonomous dependency install, a
// legitimately different and larger-blast-radius action than running
// `tsc`), so these two libraries' stubs in this repo's tsc-check
// config are hand-written from documented API shape, never cross-
// checked against the real packages' .d.ts files the way
// @supabase/supabase-js and stripe's stubs were for the other four
// functions. This is the single least-verified piece of code in this
// entire project and should be the owner's first thing to actually
// exercise once deployed, before trusting it with a real purchase.


const DOCS_BY_ID = new Map(launchSetDocuments.documents.map((d: any) => [d.id, d]));
const ALL_CLAUSES: any[] = launchSetClauses.clauses;
const LEVELS: Record<string, string> = launchSetLevels.levels;
const BASE_URL: string = launchSetMeta.baseUrl || '';

const SUPPORTED_FORMATS = ['pdf', 'docx', 'txt', 'json'] as const;
type Format = typeof SUPPORTED_FORMATS[number];

function buildContent(document: any, answers: Record<string, string>) {
  const assembled = assembleDocument(document, ALL_CLAUSES, answers);
  const jKey = classifyDocumentJurisdiction(document, ALL_CLAUSES);
  return {
    title: document.title,
    documentId: document.id,
    preparedFor: preparedForLine(document, answers),
    jurisdictionNotice: jKey && jKey !== 'NONE' ? JURISDICTION_NOTICE[jKey] : null,
    conditional: describeConditionalClauses(document, ALL_CLAUSES, answers),
    clauses: assembled.map((clause: any) => ({
      id: clause.id,
      title: clause.title,
      body: clause.renderedBody,
      kind: clause.kind,
      status: clause.status,
      edited: false,
      checkedDate: clause.checkedDate,
      citations: clause.citations || [],
      gap: clause.gap || null,
      level: clauseLevel(clause, LEVELS),
    })),
    signature: null,
    nextSteps: [],
  };
}

// Simple word-wrap against pdf-lib's own text-width measurement --
// pdf-lib (unlike pdfmake) does not paginate or wrap running text for
// you, so this is the one real piece of layout logic this function
// needs to get right itself, not something a library hides. Kept as
// its own pure function (font, size, maxWidth, text) -> string[] so
// it's at least unit-testable in isolation even without pdf-lib
// installed to run it against -- see the note at the top of this file.
function wrapText(text: string, font: any, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text.split('\n')) {
    const words = paragraph.split(' ');
    let current = '';
    for (const word of words) {
      const trial = current ? `${current} ${word}` : word;
      if (font.widthOfTextAtSize(trial, size) > maxWidth && current) {
        lines.push(current);
        current = word;
      } else {
        current = trial;
      }
    }
    lines.push(current);
  }
  return lines;
}

const PAGE_WIDTH = 612; // US Letter, points
const PAGE_HEIGHT = 792;
const MARGIN = 56;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;

async function renderPdf(content: ReturnType<typeof buildContent>): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const italic = await pdf.embedFont(StandardFonts.HelveticaOblique);

  let page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  let y = PAGE_HEIGHT - MARGIN;
  // Real content never comes closer than this to the bottom edge, so a
  // per-page footer drawn afterwards at FOOTER_Y (below this floor)
  // can never collide with it -- see the footer-drawing pass at the
  // end of this function, added for MVP_FINISH_VERIFY_SHARPEN.md item
  // 1.1 (this file previously had no per-page footer at all, unlike
  // app.js's own buildPdfDocDefinition(), which pdfmake renders from a
  // declarative `footer` callback this hand-rolled renderer has no
  // equivalent for -- pdf-lib doesn't know the final page count until
  // every page already exists, so the footer is drawn in one pass over
  // pdf.getPages() after the content loop below finishes, not inline).
  const FOOTER_Y = 26;

  function ensureSpace(lineHeight: number) {
    if (y - lineHeight < MARGIN) {
      page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
      y = PAGE_HEIGHT - MARGIN;
    }
  }

  function writeLines(text: string, font: any, size: number, color = rgb(0.1, 0.1, 0.1), gapAfter = 4) {
    const lineHeight = size * 1.3;
    for (const line of wrapText(text, font, size, CONTENT_WIDTH)) {
      ensureSpace(lineHeight);
      page.drawText(line, { x: MARGIN, y, size, font, color });
      y -= lineHeight;
    }
    y -= gapAfter;
  }

  writeLines(content.title.toUpperCase(), bold, 15, rgb(0, 0, 0), 2);
  writeLines(content.preparedFor, regular, 10, rgb(0.3, 0.32, 0.27), 10);

  if (content.jurisdictionNotice) {
    writeLines(content.jurisdictionNotice, italic, 9.5, rgb(0.3, 0.32, 0.27), 10);
  }

  if (content.conditional.length) {
    writeLines('OPTIONAL CLAUSES IN THIS DOCUMENT', bold, 10, rgb(0, 0, 0), 2);
    content.conditional.forEach((c: any) => {
      writeLines(`${c.included ? 'Included' : 'Not included'}: ${c.title} — because ${c.reason}`, regular, 10, rgb(0.1, 0.1, 0.1), 2);
    });
    y -= 8;
  }

  content.clauses.forEach((clause: any) => {
    writeLines(clause.title.toUpperCase(), bold, 12, rgb(0, 0, 0), 4);
    writeLines(clause.body, regular, 10.5);
    if (clause.kind !== 'drafting') {
      writeLines(clauseVerificationNoteText(clause, LEVELS), italic, 9, rgb(0.17, 0.43, 0.31), 4);
      clause.citations.forEach((c: any) => {
        writeLines(`"${c.quote}"`, italic, 9.5);
        writeLines(`— ${c.case}, ${c.cite} (${c.url})`, regular, 9.5, rgb(0.1, 0.1, 0.1), 6);
      });
      if (clause.gap) writeLines(`Known gap: ${clause.gap}`, regular, 9.5);
    }
    y -= 6;
  });

  writeLines('Groundtruth v1 demo · every citation shown links to a real source, labeled Cited, Verified, or Adversarially checked.', italic, 8, rgb(0.3, 0.32, 0.27));
  if (BASE_URL) {
    writeLines(`Verify this document's sourcing at: ${verifyPageUrl(BASE_URL, content.documentId)}`, italic, 8, rgb(0.3, 0.32, 0.27));
  }

  const generatedOn = new Date().toISOString().slice(0, 10);
  const pages = pdf.getPages();
  pages.forEach((pg, i) => {
    pg.drawText(`${content.documentId} · generated ${generatedOn}`, { x: MARGIN, y: FOOTER_Y, size: 8, font: regular, color: rgb(0.3, 0.32, 0.27) });
    const pageLabel = `Page ${i + 1} of ${pages.length}`;
    const labelWidth = regular.widthOfTextAtSize(pageLabel, 8);
    pg.drawText(pageLabel, { x: PAGE_WIDTH - MARGIN - labelWidth, y: FOOTER_Y, size: 8, font: regular, color: rgb(0.3, 0.32, 0.27) });
  });

  return pdf.save();
}

function buildDocxChildren(content: ReturnType<typeof buildContent>) {
  const { Paragraph, TextRun, HeadingLevel } = docx;
  const GRAY = '4B5245';
  const children: any[] = [];

  children.push(new Paragraph({ text: content.title.toUpperCase(), heading: HeadingLevel.TITLE }));
  children.push(new Paragraph({ children: [new TextRun({ text: content.preparedFor, color: GRAY })] }));

  if (content.jurisdictionNotice) {
    children.push(new Paragraph({ children: [new TextRun({ text: content.jurisdictionNotice, italics: true, color: GRAY })] }));
  }

  if (content.conditional.length) {
    children.push(new Paragraph({ text: 'OPTIONAL CLAUSES IN THIS DOCUMENT', heading: HeadingLevel.HEADING_3 }));
    content.conditional.forEach((c: any) => {
      children.push(new Paragraph({ children: [new TextRun(`${c.included ? 'Included' : 'Not included'}: ${c.title} — because ${c.reason}`)] }));
    });
  }

  content.clauses.forEach((clause: any) => {
    children.push(new Paragraph({ text: clause.title.toUpperCase(), heading: HeadingLevel.HEADING_2 }));
    children.push(new Paragraph({ children: [new TextRun(clause.body)] }));
    if (clause.kind !== 'drafting') {
      children.push(new Paragraph({ children: [new TextRun({ text: clauseVerificationNoteText(clause, LEVELS), italics: true, color: '2B6E4F' })] }));
      clause.citations.forEach((c: any) => {
        children.push(new Paragraph({ children: [new TextRun({ text: `"${c.quote}"`, italics: true })] }));
        children.push(new Paragraph({ children: [new TextRun(`— ${c.case}, ${c.cite} (${c.url})`)] }));
      });
      if (clause.gap) children.push(new Paragraph({ children: [new TextRun(`Known gap: ${clause.gap}`)] }));
    }
  });

  children.push(new Paragraph({ children: [new TextRun({ text: 'Groundtruth v1 demo · every citation shown links to a real source, labeled Cited, Verified, or Adversarially checked.', size: 16, color: GRAY })] }));
  if (BASE_URL) {
    children.push(new Paragraph({ children: [new TextRun({ text: `Verify this document's sourcing at: ${verifyPageUrl(BASE_URL, content.documentId)}`, size: 16, color: GRAY })] }));
  }
  return children;
}

async function renderDocx(content: ReturnType<typeof buildContent>): Promise<Uint8Array> {
  const { Document, Packer, Footer, Paragraph, TextRun } = docx;
  const generatedOn = new Date().toISOString().slice(0, 10);
  const doc = new Document({
    sections: [{
      children: buildDocxChildren(content),
      footers: {
        default: new Footer({
          children: [new Paragraph({ children: [new TextRun({ text: `${content.documentId} · generated ${generatedOn}`, size: 16, color: '4B5245' })] })],
        }),
      },
    }],
  });
  const buffer = await Packer.toBuffer(doc);
  return new Uint8Array(buffer);
}

Deno.serve(async req => {
  if (req.method !== 'POST') {
    return new Response(JSON.stringify({ error: 'Method not allowed' }), { status: 405 });
  }

  const dbUrl = Deno.env.get('SUPABASE_DB_URL');
  if (dbUrl) {
    const allowed = await withinRateLimit(dbUrl, callerKey(req, 'release-document'), 20);
    if (!allowed) {
      return new Response(JSON.stringify({ error: 'Too many requests. Please wait a moment and try again.' }), { status: 429 });
    }
  }

  let body: { documentId?: string; format?: string };
  try {
    body = await req.json();
  } catch {
    return new Response(JSON.stringify({ error: 'Invalid request body' }), { status: 400 });
  }
  const documentId = (body.documentId || '').trim();
  const format = (body.format || 'pdf') as Format;
  if (!documentId) {
    return new Response(JSON.stringify({ error: 'documentId is required' }), { status: 400 });
  }
  if (!SUPPORTED_FORMATS.includes(format)) {
    return new Response(JSON.stringify({ error: `format must be one of ${SUPPORTED_FORMATS.join(', ')}` }), { status: 400 });
  }
  const document = DOCS_BY_ID.get(documentId);
  if (!document) {
    // Deliberately the same message whether the id is simply wrong or
    // a real document outside the launch set -- this function is not
    // the place to reveal which ids exist and which don't.
    return new Response(JSON.stringify({ error: 'This document is not available for release.' }), { status: 404 });
  }

  const authHeader = req.headers.get('Authorization') || '';
  const userClient = createClient(
    Deno.env.get('SUPABASE_URL')!,
    Deno.env.get('SUPABASE_ANON_KEY')!,
    { global: { headers: { Authorization: authHeader } } }
  );
  const { data: userData, error: userErr } = await userClient.auth.getUser();
  if (userErr || !userData.user) {
    return new Response(JSON.stringify({ error: 'Not authenticated' }), { status: 401 });
  }

  // Same function the RLS policies themselves call -- this is a real
  // entitlement check, not a parallel reimplementation of one, so this
  // function and the database's own write-time policies can't
  // silently disagree about who's entitled to what.
  const { data: entitled, error: entitledErr } = await userClient.rpc('has_active_entitlement', {
    for_document_id: documentId,
  });
  if (entitledErr) {
    return new Response(JSON.stringify({ error: 'Could not check entitlement status.' }), { status: 500 });
  }
  if (!entitled) {
    return new Response(JSON.stringify({ error: 'This document has not been purchased, or its purchase window/re-export limit has been reached.' }), { status: 403 });
  }

  const { data: agreement, error: agreementErr } = await userClient
    .from('agreements')
    .select('id, answers')
    .eq('document_id', documentId)
    .eq('user_id', userData.user.id)
    .order('generated_at', { ascending: false })
    .limit(1)
    .maybeSingle();
  if (agreementErr || !agreement) {
    return new Response(JSON.stringify({ error: 'No saved document found to release. Generate it first, then purchase it.' }), { status: 404 });
  }

  const content = buildContent(document, agreement.answers || {});
  const plainText = buildPlainText(content);
  const outputHash = hashString(plainText);

  let bytes: Uint8Array;
  let contentType: string;
  let ext: string;
  if (format === 'pdf') {
    bytes = await renderPdf(content);
    contentType = 'application/pdf';
    ext = 'pdf';
  } else if (format === 'docx') {
    bytes = await renderDocx(content);
    contentType = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
    ext = 'docx';
  } else if (format === 'txt') {
    bytes = new TextEncoder().encode(plainText);
    contentType = 'text/plain';
    ext = 'txt';
  } else {
    bytes = new TextEncoder().encode(JSON.stringify(content, null, 2));
    contentType = 'application/json';
    ext = 'json';
  }

  const admin = createClient(
    Deno.env.get('SUPABASE_URL')!,
    Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
  );

  const objectPath = `${userData.user.id}/${documentId}/${Date.now()}.${ext}`;
  const { error: uploadErr } = await admin.storage.from('documents').upload(objectPath, bytes, {
    contentType,
    upsert: false,
  });
  if (uploadErr) {
    return new Response(JSON.stringify({ error: `Could not store the rendered document: ${uploadErr.message}` }), { status: 500 });
  }

  // 5 minutes -- long enough for the browser to start the download it
  // already triggered this request for, short enough that the URL
  // isn't a durable, sharable link to someone else's document.
  const { data: signed, error: signErr } = await admin.storage
    .from('documents')
    .createSignedUrl(objectPath, 300);
  if (signErr || !signed) {
    return new Response(JSON.stringify({ error: 'Could not create a download link.' }), { status: 500 });
  }

  await admin.from('audit_log').insert({
    user_id: userData.user.id,
    document_id: documentId,
    corpus_version: null,
    clause_ids: content.clauses.map((c: any) => c.id),
    clause_checked_dates: Object.fromEntries(content.clauses.map((c: any) => [c.id, c.checkedDate || null])),
    output_hash: outputHash,
  });

  // The actual re-export-count enforcement: has_active_entitlement()
  // already checked exports_used < exports_allowed above, but checking
  // alone doesn't consume anything -- this is the one statement that
  // makes that limit real instead of a column nothing ever increments
  // (MVP_SPEC_STATUS.md's own earlier finding). Best-effort: a failure
  // here means an export was already handed out but not counted,
  // which undercounts in the owner's favor, not a security hole, so
  // this does not fail the whole request.
  const { error: incrErr } = await admin.rpc('increment_exports_used', { for_document_id: documentId, for_user_id: userData.user.id });
  if (incrErr) {
    console.error('release-document: could not increment exports_used', incrErr);
  }

  return new Response(
    JSON.stringify({ url: signed.signedUrl, format, expiresInSeconds: 300 }),
    { headers: { 'Content-Type': 'application/json' } }
  );
});
